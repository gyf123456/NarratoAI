#!/usr/bin/env python
# -*- coding: UTF-8 -*-

"""
@Project: 影视解说-解说文案
@File   : narration_copy.py
@Description: 生成可供用户审核修改的影视解说正文
"""

from ..base import ParameterizedPrompt, PromptMetadata, ModelType, OutputFormat


class NarrationCopyPrompt(ParameterizedPrompt):
    """影视解说正文生成提示词"""

    def __init__(self):
        metadata = PromptMetadata(
            name="narration_copy",
            category="film_tv_narration",
            version="v1.0",
            description="基于剧情理解和字幕生成可审核修改的影视解说正文，不绑定时间戳",
            model_type=ModelType.TEXT,
            output_format=OutputFormat.TEXT,
            tags=["影视", "解说文案", "电影解说", "剧情承接", "用户审核"],
            parameters=[
                "drama_name",
                "drama_genre",
                "plot_analysis",
                "subtitle_content",
                "narration_language",
                "narration_word_count",
            ],
        )
        super().__init__(metadata, required_parameters=["drama_name", "plot_analysis", "subtitle_content"])

        self._system_prompt = (
            "你是一位注重背景、全局格局和人物动机的影视解说作者。你只输出可供用户审核修改的解说正文，"
            "不要输出JSON、时间戳、编号、标题、解释或Markdown。"
        )

    def get_template(self) -> str:
        return """# 影视解说正文创作任务

## 目标
为影视作品《${drama_name}》创作一份可直接给用户审核修改的解说文案正文。此阶段不做画面匹配，不输出时间戳。

## 剧情理解材料
<plot>
${plot_analysis}
</plot>

## 原始字幕
<subtitles>
${subtitle_content}
</subtitles>

## 输出语言
<narration_language>
${narration_language}
</narration_language>

## 用户选择的影视类型
<drama_genre>
${drama_genre}
</drama_genre>

## 用户要求的文案字数
<narration_word_count>
${narration_word_count}
</narration_word_count>

## 类型写作规则
必须按用户选择的影视类型调整表达重点，不要自行改判类型：
- 剧情/情感：突出人物选择、关系裂痕、命运压力和情绪余波。
- 悬疑/犯罪：突出线索、疑点、动机、误导和未揭开的真相。
- 动作/冒险：突出目标、危险升级、身体对抗和关键抉择。
- 喜剧/轻松：突出误会、反差、节奏包袱和人物可爱处。
- 科幻/奇幻：突出设定规则、未知威胁、世界观反差和代价。
- 历史/战争：突出时代处境、阵营选择、牺牲和局势变化。
- 恐怖/惊悚：突出异常细节、压迫感、未知危险和心理悬念。
- 自定义类型：严格服从用户填写的类型方向。

## 开头钩子公式
开头必须使用“人物困境 + 反常信息 + 悬念问题”：
1. 先点出主角或关键人物正在面对什么压力。
2. 再抛出一个违背常识、关系突变或危险升级的信息。
3. 最后留下观众想继续看的问题：他为什么这样做、谁在撒谎、这场选择会把所有人推向哪里。

## 写作规则
1. 必须使用 ${narration_language}。
2. 严格基于剧情理解和字幕事实，不编造核心情节、身份、结局。
3. 先写清楚人物动机和因果链，再写情绪金句；不要只堆形容词。
4. 每句话只表达一个信息点，适合后续按句匹配画面。
5. 句子尽量短，单句优先 15-35 字；信息复杂时拆成多句。
6. 每 2-3 句要有明确承接，让观众知道为什么从上一幕来到下一幕。
   开场钩子后先交代本集的主要人物、处境和核心冲突，让没有看过原片的观众也能理解剧情梗概。
   以完整的剧情段落组织正文：人物是谁、想做什么、遇到什么阻碍、事件如何改变局势。短句只是朗读单位，不是必须逐句剪切的单位。
   多条人物线应分段讲清楚，一条线讲到一个阶段性结果后再转入下一条；转场要明确人物或地点变化，不能在几条支线之间反复跳切。
   首次出现的重要人物说明身份和与主线的关系；删去不影响本集主线的支线和名词，避免短时间堆出大量人名。
   保留“传闻、指控、人物的判断”和已确认事实的区别；没有证据的谋杀指控不得写成确定的凶手结论。
7. 总长度以 ${narration_word_count} 字为目标，允许上下浮动 10%；中日韩语言按非空白字符计数，其他语言按单词计数。不得再套用固定长度区间。
8. 不要使用编号、项目符号、章节标题或括号说明。

## 背景与观点
- 开场提出一个由本集事实支持的观察角度，再补充理解冲突必需的背景：谁掌握权力、各方想得到什么、彼此怎样依赖或制约。不要用一串没有解释的人名代替背景。
- 整篇正文用这个观察角度串联人物线；每次推进关键事件，都说明它怎样改变家族关系、利益分配或人物处境，避免只复述谁做了什么。
- 在篇幅允许的情况下，每个主要剧情段落加入一到两句具体判断，按“剧情证据 -> 动机或机制 -> 作者判断”展开。观点必须落在当前事件上，不能只有空泛金句。
- 可以分析制度、身份、婚姻、责任、信息差等因素怎样影响选择；人物的动机如果没有直接证据，应使用“在我看来”“可以理解为”“这让人看到”等措辞明确是解读，不把推测写成事实。
- 允许评价人物的选择，也要说明他掌握的信息、面临的限制和付出的代价，避免简单贴善恶或聪明愚蠢的标签。
- 背景只能来自给定剧情材料和已提供的可信背景资料；缺少依据时收缩表述，不能编造历史、人物关系、幕后真相或引用后续剧情来证明当前判断。
- 剧情要足够清楚，观点才有说服力。不要为增加评论挤掉关键因果，不要在每句话里机械重复“我认为”。
- 结尾回到开场的观察角度，用本集已经发生的结果提出自己的判断，再留下本集尚未解决的问题。

## 输出要求
只输出解说正文。不要输出 JSON、时间戳、代码块或任何解释。"""
